// NCBI BLAST+ 2.17.0+: f64 coefficients and operation order are retained.
// A small private high/low compatibility helper supplies the four extended
// exp/divide/multiply expressions; it is not an upstream function translation.

pub fn erf_impl(z: f64, mut invert: bool) -> f64 {
    if z < 0.0 {
        if !invert {
            return -erf_impl(-z, invert);
        } else if z < -0.5 {
            return 2.0 - erf_impl(-z, invert);
        } else {
            return 1.0 + erf_impl(-z, false);
        }
    }

    let mut result: f64;

    /* Big bunch of selection statements now to pick
    which implementation to use,
    try to put most likely options first: */
    if z < 0.5 {
        /* We're going to calculate erf: */
        if z < 1e-10 {
            if z == 0.0 {
                result = 0.0;
            } else {
                const C: f64 = 0.003379167095512573896158903121545171688;
                result = z * 1.125 + z * C;
            }
        } else {
            /* Maximum Deviation Found:                     1.561e-17
            Expected Error Term:                         1.561e-17
            Maximum Relative Change in Control Points:   1.155e-04
            Max Error found at double precision =        2.961182e-17 */

            const Y: f64 = 1.044948577880859375;
            const P: [f64; 5] = [
                0.0834305892146531832907,
                -0.338165134459360935041,
                -0.0509990735146777432841,
                -0.00772758345802133288487,
                -0.000322780120964605683831,
            ];

            const Q: [f64; 5] = [
                1.0,
                0.455004033050794024546,
                0.0875222600142252549554,
                0.00858571925074406212772,
                0.000370900071787748000569,
            ];

            let zz = z * z;

            let p = (((P[4] * zz + P[3]) * zz + P[2]) * zz + P[1]) * zz + P[0];
            let q = (((Q[4] * zz + Q[3]) * zz + Q[2]) * zz + Q[1]) * zz + Q[0];

            result = z * (Y + p / q);
        }
    } else if if invert { z < 28.0 } else { z < 5.8 } {
        /* We'll be calculating erfc: */
        invert = !invert;

        if z < 1.5 {
            /* Maximum Deviation Found:                     3.702e-17
            Expected Error Term:                         3.702e-17
            Maximum Relative Change in Control Points:   2.845e-04
            Max Error found at double precision =        4.841816e-17 */
            const Y: f64 = 0.405935764312744140625;
            const P: [f64; 6] = [
                -0.098090592216281240205,
                0.178114665841120341155,
                0.191003695796775433986,
                0.0888900368967884466578,
                0.0195049001251218801359,
                0.00180424538297014223957,
            ];

            const Q: [f64; 7] = [
                1.0,
                1.84759070983002217845,
                1.42628004845511324508,
                0.578052804889902404909,
                0.12385097467900864233,
                0.0113385233577001411017,
                0.337511472483094676155e-5,
            ];

            let x = z - 0.5;
            let p = ((((P[5] * x + P[4]) * x + P[3]) * x + P[2]) * x + P[1]) * x + P[0];
            let q = ((((Q[5] * x + Q[4]) * x + Q[3]) * x + Q[2]) * x + Q[1]) * x + Q[0];

            result = Y + p / q;
            result = extended_exp_product(result, z);
        } else if z < 2.5 {
            /* Max Error found at double precision =        6.599585e-18
            Maximum Deviation Found:                     3.909e-18
            Expected Error Term:                         3.909e-18
            Maximum Relative Change in Control Points:   9.886e-05 */
            const Y: f64 = 0.50672817230224609375;
            const P: [f64; 6] = [
                -0.0243500476207698441272,
                0.0386540375035707201728,
                0.04394818964209516296,
                0.0175679436311802092299,
                0.00323962406290842133584,
                0.000235839115596880717416,
            ];

            const Q: [f64; 6] = [
                1.0,
                1.53991494948552447182,
                0.982403709157920235114,
                0.325732924782444448493,
                0.0563921837420478160373,
                0.00410369723978904575884,
            ];

            let x = z - 1.5;
            let p = ((((P[5] * x + P[4]) * x + P[3]) * x + P[2]) * x + P[1]) * x + P[0];
            let q = ((((Q[5] * x + Q[4]) * x + Q[3]) * x + Q[2]) * x + Q[1]) * x + Q[0];

            result = Y + p / q;
            result = extended_exp_product(result, z);
        } else if z < 4.5 {
            /* Maximum Deviation Found:                     1.512e-17
            Expected Error Term:                         1.512e-17
            Maximum Relative Change in Control Points:   2.222e-04
            Max Error found at double precision =        2.062515e-17 */
            const Y: f64 = 0.5405750274658203125;
            const P: [f64; 6] = [
                0.00295276716530971662634,
                0.0137384425896355332126,
                0.00840807615555585383007,
                0.00212825620914618649141,
                0.000250269961544794627958,
                0.113212406648847561139e-4,
            ];

            const Q: [f64; 6] = [
                1.0,
                1.04217814166938418171,
                0.442597659481563127003,
                0.0958492726301061423444,
                0.0105982906484876531489,
                0.000479411269521714493907,
            ];

            let x = z - 3.5;
            let p = ((((P[5] * x + P[4]) * x + P[3]) * x + P[2]) * x + P[1]) * x + P[0];
            let q = ((((Q[5] * x + Q[4]) * x + Q[3]) * x + Q[2]) * x + Q[1]) * x + Q[0];

            result = Y + p / q;
            result = extended_exp_product(result, z);
        } else {
            /* Max Error found at double precision =        2.997958e-17
            Maximum Deviation Found:                     2.860e-17
            Expected Error Term:                         2.859e-17
            Maximum Relative Change in Control Points:   1.357e-05 */
            const Y: f64 = 0.5579090118408203125;
            const P: [f64; 7] = [
                0.00628057170626964891937,
                0.0175389834052493308818,
                -0.212652252872804219852,
                -0.687717681153649930619,
                -2.5518551727311523996,
                -3.22729451764143718517,
                -2.8175401114513378771,
            ];

            const Q: [f64; 7] = [
                1.0,
                2.79257750980575282228,
                11.0567237927800161565,
                15.930646027911794143,
                22.9367376522880577224,
                13.5064170191802889145,
                5.48409182238641741584,
            ];

            let x = 1.0 / z;
            let p =
                (((((P[6] * x + P[5]) * x + P[4]) * x + P[3]) * x + P[2]) * x + P[1]) * x + P[0];
            let q =
                (((((Q[6] * x + Q[5]) * x + Q[4]) * x + Q[3]) * x + Q[2]) * x + Q[1]) * x + Q[0];

            result = Y + p / q;
            result = extended_exp_product(result, z);
        }
    } else {
        /* Any value of z larger than 28 will underflow to zero: */
        result = 0.0;
        invert = !invert;
    }

    if invert {
        result = 1.0 - result;
    }

    return result;
}

pub fn erf(z: f64) -> f64 {
    return erf_impl(z, false);
}

pub fn erf_c(z: f64) -> f64 {
    return erf_impl(z, true);
}

/// Private compatibility arithmetic for the original expl expression only.
/// The rest of Boost's approximation is evaluated in f64 exactly as in C.
#[derive(Clone, Copy)]
struct HighLow {
    hi: f64,
    lo: f64,
}
impl HighLow {
    fn from(value: f64) -> Self {
        Self { hi: value, lo: 0.0 }
    }
    fn sum(a: f64, b: f64) -> Self {
        let hi = a + b;
        let v = hi - a;
        let lo = (a - (hi - v)) + (b - v);
        Self { hi, lo }
    }
    fn add(self, other: Self) -> Self {
        let first = Self::sum(self.hi, other.hi);
        Self::sum(first.hi, (first.lo + self.lo) + other.lo)
    }
    fn neg(self) -> Self {
        Self {
            hi: -self.hi,
            lo: -self.lo,
        }
    }
    fn sub(self, other: Self) -> Self {
        self.add(other.neg())
    }
    fn mul(self, other: Self) -> Self {
        let hi = self.hi * other.hi;
        let lo = self.hi.mul_add(other.hi, -hi)
            + self.hi * other.lo
            + self.lo * other.hi
            + self.lo * other.lo;
        Self::sum(hi, lo)
    }
    fn mul_scalar(self, other: f64) -> Self {
        let hi = self.hi * other;
        let lo = self.hi.mul_add(other, -hi) + self.lo * other;
        Self::sum(hi, lo)
    }
    fn div_scalar(self, other: f64) -> Self {
        let q1 = self.hi / other;
        let residual = self.sub(Self::from(q1).mul_scalar(other));
        let q2 = residual.hi / other;
        let residual = residual.sub(Self::from(q2).mul_scalar(other));
        let q3 = (residual.hi + residual.lo) / other;
        Self::sum(q1, q2).add(Self::from(q3))
    }
    fn exp_reduced(x: f64) -> (Self, i32) {
        let power = (x * std::f64::consts::LOG2_E).round() as i32;
        let ln2 = Self {
            hi: std::f64::consts::LN_2,
            lo: 2.31904681384629955842e-17,
        };
        let residual = Self::from(x).sub(ln2.mul_scalar(power as f64));
        let mut term = Self::from(1.0);
        let mut result = term;
        for i in 1..=30 {
            term = term.mul(residual).div_scalar(i as f64);
            result = result.add(term);
        }
        (result, power)
    }
    fn round_extended(self) -> Self {
        // The pinned GNU reference uses a 64-bit-significand long double.
        // hi has 53 significand bits, leaving eleven low bits to retain.
        let exponent = ((self.hi.to_bits() >> 52) & 0x7ff) as i32 - 1023;
        let quantum = f64::from_bits(((exponent - 63 + 1023) as u64) << 52);
        let units = (self.lo / quantum).round_ties_even();
        Self::sum(self.hi, units * quantum)
    }
    fn round_scaled(self, power: i32) -> f64 {
        if self.hi == 0.0 {
            return self.hi;
        }
        let bits = self.hi.to_bits();
        let exponent = ((bits >> 52) & 0x7ff) as i32 - 1023;
        let scaled_exponent = exponent + power;
        if scaled_exponent >= -1022 {
            // self.hi already rounds the high/low sum to nearest f64. A normal
            // power-of-two rescaling retains that rounding without losing lo.
            return f64::from_bits(
                (bits & 0x000fffffffffffff) | (((scaled_exponent + 1023) as u64) << 52),
            );
        }
        // Round in units of the least subnormal, avoiding an intermediate
        // underflow of exp(x) or double rounding at the normal/subnormal edge.
        let scale = f64::from_bits(((power + 1074 + 1023) as u64) << 52);
        let hi = self.hi * scale;
        let lo = self.lo * scale;
        let integral = hi.floor();
        let fraction = Self::sum(hi - integral, lo);
        let integer = integral as u64;
        let up = fraction.hi > 0.5
            || (fraction.hi == 0.5
                && (fraction.lo > 0.0 || (fraction.lo == 0.0 && integer & 1 != 0)));
        f64::from_bits(integer + up as u64)
    }
}
fn extended_exp_product(result: f64, z: f64) -> f64 {
    // In the source, -z*z is rounded as DOUBLE before promotion to expl.
    let argument = (-z) * z;
    let (value, power) = HighLow::exp_reduced(argument);
    value
        .round_extended()
        .div_scalar(z)
        .round_extended()
        .mul_scalar(result)
        .round_extended()
        .round_scaled(power)
}
